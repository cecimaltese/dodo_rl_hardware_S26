"""
real2sim.py — what a motor reading means as a sim joint angle, in ONE place.

A motor reports in its own units: a Damiao in radians at its output shaft, an ODrive
in turns of the MOTOR shaft. A sim joint angle (the URDF's / Isaac Lab's / MuJoCo's
radians, the policy's units) is

    q = sign * (raw - zero) * scale        scale = 1 (Damiao), 2*pi / ratio (ODrive)

  motor  which motor drives the joint            measured: calibrate_joints.py
  sign   +1 if the reading grows with the sim's +angle         measured, same
  zero   the raw reading at q = 0                               measured, same
  ratio  motor turns per joint turn (knee/ankle gearing)        fleet_config.GEAR_RATIO

motor/sign/zero live in joint_calib.py (generated by calibrate_joints.py, which also
records the ratio each entry was made with); ratio lives in fleet_config.py. Every
tool that turns a reading into an angle goes through here, so they can't disagree
about what a reading means — the visualizer, calibrate_joints.py and motor_service.py
(unit scale only, until the measured sign/zero layer is wired in: HANDOFF §2).

Import-only: nothing here opens a bus.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, replace
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import fleet_config

TWO_PI = 2.0 * math.pi
CALIB_PATH = Path(__file__).resolve().parent / "joint_calib.py"

ODRIVE_MOTORS = frozenset(c.name for c in fleet_config.OD_JOINTS)
DAMIAO_MOTORS = frozenset(c.name for c in fleet_config.DM_JOINTS)
JOINTS = tuple(c.name for c in (*fleet_config.DM_JOINTS, *fleet_config.OD_JOINTS))


def is_odrive(motor: str) -> bool:
    return motor in ODRIVE_MOTORS


def gear_ratio(joint: str) -> float:
    """Motor turns per joint turn. 1.0 for direct drive, and for an ODrive joint whose
    ratio isn't measured yet (fleet_config.GEAR_RATIO None) — see ratio_known()."""
    r = fleet_config.GEAR_RATIO.get(joint)
    return 1.0 if r is None else float(r)


def ratio_known(joint: str) -> bool:
    return not is_odrive(joint) or fleet_config.GEAR_RATIO.get(joint) is not None


def rad_per_native(joint: str, motor: Optional[str] = None) -> float:
    """Joint radians per native unit of `motor` (default: the motor named like the
    joint), i.e. the scale in q = sign * (raw - zero) * scale."""
    motor = joint if motor is None else motor
    return TWO_PI / gear_ratio(joint) if is_odrive(motor) else 1.0


@dataclass(frozen=True)
class JointCal:
    """One joint's reading <-> angle map. `measured` False = an identity placeholder
    (motor named like the joint, sign +1, zero 0): unit conversion only."""
    joint: str
    motor: str
    sign: int = 1
    zero: float = 0.0
    ratio: float = 1.0
    measured: bool = False

    @property
    def scale(self) -> float:
        return TWO_PI / self.ratio if is_odrive(self.motor) else 1.0

    def to_sim(self, raw: float) -> float:
        return self.sign * (raw - self.zero) * self.scale

    def vel_to_sim(self, raw_vel: float) -> float:
        return self.sign * raw_vel * self.scale

    def to_raw(self, q: float) -> float:
        return self.zero + self.sign * q / self.scale

    def zeroed_at(self, raw_now: float, q_now: float = 0.0) -> "JointCal":
        """The same map, re-zeroed so that `raw_now` reads `q_now`."""
        return replace(self, zero=raw_now - self.sign * q_now / self.scale)


def read_calib(path=CALIB_PATH) -> dict:
    """joint_calib.py's raw dict, or {} if there isn't one. Exec'd rather than
    imported so any path works and a stale sys.modules entry can't win."""
    ns: dict = {}
    try:
        with open(path) as f:
            exec(compile(f.read(), str(path), "exec"), ns)
    except FileNotFoundError:
        return {}
    return dict(ns.get("JOINT_CALIB", {}))


def entry_ratio_problem(joint: str, entry: dict) -> Optional[str]:
    """Why a joint_calib entry can't be used with today's GEAR_RATIO, or None.
    Entries from before 2026-11-04 carry no ratio: they were made assuming 1."""
    if not is_odrive(entry.get("motor", joint)):
        return None
    made, now = float(entry.get("ratio", 1.0)), gear_ratio(joint)
    if abs(made - now) > 1e-9:
        return (f"{joint}: calibrated with gear ratio {made:g}, fleet_config.GEAR_RATIO "
                f"now says {now:g}. Redo it: calibrate_joints.py --only {joint}")
    return None


def stops(path=CALIB_PATH) -> Dict[str, Tuple[float, float]]:
    """Each joint's measured hard stops in sim radians, (sim_lo, sim_hi): the durable
    half of joint_calib.py. A joint without both, or whose entry today's gear ratio
    refuses, is left out, never guessed."""
    out = {}
    for j, e in read_calib(path).items():
        if (e.get("sim_lo") is not None and e.get("sim_hi") is not None
                and entry_ratio_problem(j, e) is None):
            out[j] = (float(e["sim_lo"]), float(e["sim_hi"]))
    return out


def command_band(joint: str, path=CALIB_PATH,
                 margin: float = None) -> Optional[Tuple[float, float]]:
    """Where a position command for `joint` may go, in sim radians: the measured stops
    pulled in by fleet_config.STOP_MARGIN_RAD. None if the stops aren't measured."""
    s = stops(path).get(joint)
    if s is None:
        return None
    m = fleet_config.STOP_MARGIN_RAD if margin is None else margin
    return (s[0] + m, s[1] - m)


def load(path=CALIB_PATH) -> Tuple[Dict[str, JointCal], List[str]]:
    """Every fleet joint's map, and warnings. A joint with no usable joint_calib entry
    gets the identity placeholder (measured=False), never a guess."""
    entries = read_calib(path)
    cals: Dict[str, JointCal] = {}
    warnings: List[str] = []
    for j in JOINTS:
        e = entries.get(j)
        motor = (e or {}).get("motor", j)
        ratio = gear_ratio(j) if is_odrive(motor) else 1.0
        problem = entry_ratio_problem(j, e) if e else None
        if e and e.get("zero") is not None and problem is None:
            cals[j] = JointCal(j, motor, int(e["sign"]), float(e["zero"]), ratio, True)
            if is_odrive(motor):
                warnings.append(f"{j}: its zero is from joint_calib.py, but an ODrive zeroes "
                                f"its encoder at power-up: valid only if the drive hasn't "
                                f"been power-cycled since (else --home, or --zero-start)")
        else:
            if problem:
                warnings.append(problem)
            cals[j] = JointCal(j, j, 1, 0.0, ratio, False)
        if not ratio_known(j):
            warnings.append(f"{j}: gear ratio not measured (fleet_config.GEAR_RATIO), "
                            f"reading as direct drive: its angle is off by that factor")
    return cals, warnings
